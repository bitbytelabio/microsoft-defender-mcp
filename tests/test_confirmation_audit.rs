#[tokio::test]
async fn test_credential_exclusion_sweep() {
    let upstream_mock = spawn_mock(create_upstream_app()).await;
    let scratch = ScratchDir::new("cred-exclusion-sweep");
    let audit_file = scratch.0.join("audit.jsonl");

    let all_flags = &[
        "--enable-live-response",
        "--enable-device-response",
        "--enable-offboarding",
        "--enable-indicators",
        "--enable-triage",
        "--audit-log",
        audit_file.to_str().unwrap(),
    ];
    let envs = &[
        (
            "DEFENDER_ENDPOINT_BASE_URL",
            upstream_mock.base_url.as_str(),
        ),
        (
            "DEFENDER_AUTHORITY_BASE_URL",
            upstream_mock.base_url.as_str(),
        ),
        ("GRAPH_BASE_URL", upstream_mock.base_url.as_str()),
    ];

    let actions = all_26_mutating_actions();
    let mut combined_stderr = String::new();

    // 1. Mode: accepted (all 26 succeed)
    {
        let mut proc = McpProcess::initialize_with_elicitation(
            all_flags,
            envs,
            ElicitationResponse::AcceptConfirm,
        );
        for (tool, action, valid_args, _) in &actions {
            let res = proc.call_tool(tool, valid_args.clone());
            assert_ne!(
                res["result"]["isError"],
                json!(true),
                "accepted failed for {tool}.{action}: {res}"
            );
        }
        combined_stderr.push_str(&proc.captured_stderr());
        assert!(proc.shutdown().success());
    }

    // 2. Mode: declined (19 destructive fail with not_confirmed, 7 triage proceed)
    {
        let mut proc =
            McpProcess::initialize_with_elicitation(all_flags, envs, ElicitationResponse::Decline);
        for (tool, action, valid_args, _) in &actions {
            let res = proc.call_tool(tool, valid_args.clone());
            if *tool != "defender_triage" {
                assert_eq!(
                    res["result"]["isError"],
                    json!(true),
                    "destructive {tool}.{action} must be declined"
                );
                assert_eq!(
                    res["result"]["structuredContent"]["code"],
                    json!("not_confirmed")
                );
            } else {
                assert_ne!(
                    res["result"]["isError"],
                    json!(true),
                    "triage {action} does not prompt"
                );
            }
        }
        combined_stderr.push_str(&proc.captured_stderr());
        assert!(proc.shutdown().success());
    }

    // 3. Mode: rejected (all 26 fail locally due to validation error before network)
    {
        let mut proc = McpProcess::initialize_with_elicitation(
            all_flags,
            envs,
            ElicitationResponse::AcceptConfirm,
        );
        for (tool, action, _, invalid_args) in &actions {
            let res = proc.call_tool(tool, invalid_args.clone());
            assert_eq!(
                res["result"]["isError"],
                json!(true),
                "invalid input for {tool}.{action} must fail: {res}"
            );
        }
        combined_stderr.push_str(&proc.captured_stderr());
        assert!(proc.shutdown().success());
    }

    // 4. Mode: confirmation unavailable (19 destructive fail with confirmation_unavailable, 7 triage proceed)
    {
        let mut proc = McpProcess::start(all_flags, envs);
        for (tool, action, valid_args, _) in &actions {
            let res = proc.call_tool(tool, valid_args.clone());
            if *tool != "defender_triage" {
                assert_eq!(
                    res["result"]["isError"],
                    json!(true),
                    "destructive {tool}.{action} must fail when unavailable"
                );
                assert_eq!(
                    res["result"]["structuredContent"]["code"],
                    json!("confirmation_unavailable")
                );
            } else {
                assert_ne!(
                    res["result"]["isError"],
                    json!(true),
                    "triage {action} proceeds without elicitation"
                );
            }
        }
        combined_stderr.push_str(&proc.captured_stderr());
        assert!(proc.shutdown().success());
    }

    // 5. User-mode: sign-in, renewal, renewal failure through MockIdp
    let idp = MockIdp::start().await;
    // Initial token grants for startup
    idp.queue_audience_response(
        Audience::Endpoint,
        AudienceResponse::Success {
            scopes: vec!["Machine.ReadWrite".into()],
            expires_in: 0, // Immediately expired so next call triggers renewal
        },
    );
    idp.set_audience_response(
        Audience::Graph,
        AudienceResponse::Success {
            scopes: vec!["SecurityAlert.ReadWrite.All".into()],
            expires_in: 3600,
        },
    );
    // Renewal 1: succeeds (returns new tokens)
    idp.queue_audience_response(
        Audience::Endpoint,
        AudienceResponse::Success {
            scopes: vec!["Machine.ReadWrite".into()],
            expires_in: 0,
        },
    );
    // Renewal 2: fails with AADSTS700082
    idp.queue_audience_response(Audience::Endpoint, AudienceResponse::Aadsts(700082));

    let user_flags = &[
        "--auth-mode",
        "user",
        "--sign-in-flow",
        "browser",
        "--enable-live-response",
        "--audit-log",
        audit_file.to_str().unwrap(),
    ];
    let user_envs = &[
        ("DEFENDER_AUTHORITY_BASE_URL", idp.base_url.as_str()),
        ("DEFENDER_TEST_BROWSER_CMD", MockIdp::browser_cmd()),
        (
            "DEFENDER_ENDPOINT_BASE_URL",
            upstream_mock.base_url.as_str(),
        ),
        ("GRAPH_BASE_URL", upstream_mock.base_url.as_str()),
    ];

    {
        let mut proc_user = McpProcess::initialize_with_elicitation(
            user_flags,
            user_envs,
            ElicitationResponse::AcceptConfirm,
        );

        // Call 1: triggers renewal, renewal succeeds
        let res1 = proc_user.call_tool("defender_response", collect_args());
        assert_ne!(
            res1["result"]["isError"],
            json!(true),
            "user mode call with renewal must succeed: {res1}"
        );

        // Call 2: triggers renewal, renewal fails with session expired
        let res2 = proc_user.call_tool("defender_response", collect_args());
        assert_eq!(
            res2["result"]["isError"],
            json!(true),
            "renewal failure must return error"
        );
        assert_eq!(
            res2["result"]["structuredContent"]["code"],
            json!("reauthentication_required")
        );

        combined_stderr.push_str(&proc_user.captured_stderr());
        assert!(proc_user.shutdown().success());
    }

    // Extract PKCE verifier recorded by MockIdp
    let verifiers: Vec<String> = idp
        .recorded_tokens()
        .iter()
        .filter_map(|t| t.code_verifier.clone())
        .collect();
    assert!(
        !verifiers.is_empty(),
        "IdP must have recorded PKCE code verifier"
    );

    // 6. Assertions on Audit Log & captured stderr
    let records = read_audit_records(&audit_file);
    assert!(
        records.len() >= 140,
        "every mutating attempt must produce audit records, got {}",
        records.len()
    );

    let audit_content = std::fs::read_to_string(&audit_file).expect("read audit file");

    let sentinels = [
        "SENTINEL-CS-",
        "SENTINEL-AT-",
        "SENTINEL-RT-",
        "SENTINEL-CODE-",
        "SENTINEL-DC-",
    ];

    for sentinel in sentinels {
        assert!(
            !audit_content.contains(sentinel),
            "audit log must not contain sentinel {sentinel}"
        );
        assert!(
            !combined_stderr.contains(sentinel),
            "stderr must not contain sentinel {sentinel}"
        );
    }

    for verifier in &verifiers {
        assert!(
            !audit_content.contains(verifier),
            "audit log must not contain PKCE code verifier {verifier}"
        );
        assert!(
            !combined_stderr.contains(verifier),
            "stderr must not contain PKCE code verifier {verifier}"
        );
    }
}
