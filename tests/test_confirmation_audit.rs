#[tokio::test]
async fn test_confirm_accepted_runs_upstream_and_records_elicitations() {
    let mock = spawn_mock(create_upstream_app()).await;
    let scratch = ScratchDir::new("confirm-accept");
    let audit_file = scratch.0.join("audit.jsonl");

    let mut proc = McpProcess::initialize_with_elicitation(
        &[
            "--enable-live-response",
            "--audit-log",
            audit_file.to_str().unwrap(),
        ],
        &[
            ("DEFENDER_ENDPOINT_BASE_URL", &mock.base_url),
            ("DEFENDER_AUTHORITY_BASE_URL", &mock.base_url),
        ],
        ElicitationResponse::AcceptConfirm,
    );

    let res = proc.call_tool("defender_response", collect_args());
    assert_ne!(res["result"]["isError"], json!(true), "{res:?}");
    assert_eq!(res["result"]["structuredContent"]["id"], ACTION_ID);

    // 1 upstream hit to the collection endpoint
    mock.assert_hits(
        &format!("/api/machines/{MACHINE}/collectInvestigationPackage"),
        1,
    );

    // Elicitation message asserts prompt text per template
    let messages = proc.recorded_elicitations();
    assert_eq!(messages.len(), 1, "expected 1 elicitation message");
    let msg = &messages[0];
    assert!(msg.contains("Confirm destructive Microsoft Defender action"));
    assert!(msg.contains("Tool:    defender_response"));
    assert!(msg.contains("Action:  collect_investigation_package"));
    assert!(msg.contains(MACHINE));
    assert!(msg.contains(COMMENT));
    assert!(msg.contains("Acting as:"));
    assert!(
        msg.contains("This request was generated by an AI agent. Approve only if you intended it.")
    );

    assert!(proc.shutdown().success());
}

