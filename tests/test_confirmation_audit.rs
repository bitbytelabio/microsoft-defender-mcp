use std::sync::Arc;
const MACHINE: &str = "1e5bc9d7e413ddd7902c2932e418702b84d0cc07";
const ACTION_ID: &str = "7327b54fd718525cbca07dacde913b5ac3c85673";
const COMMENT: &str = "Incident 4124 triage collection";
const SHA1: &str = "87662bc3d60e4200ceaf7aae249d1c343f4b83c9";

fn collect_args() -> Value {
    json!({
        "action": "collect_investigation_package",
        "machine_id": MACHINE,
        "comment": COMMENT,
    })
}

fn create_upstream_app() -> axum::Router {
    axum::Router::new().fallback(|req: axum::extract::Request| async move {
        let method = req.method().to_string();
        let path = req.uri().path().to_string();

        if method == "POST" && path.ends_with("/oauth2/v2.0/token") {
            axum::Json(json!({
                "token_type": "Bearer",
                "access_token": SENTINEL_APP_TOKEN,
                "expires_in": 3600
            }))
            .into_response()
        } else if method == "DELETE" || (method == "POST" && path == "/api/indicators/BatchDelete")
        {
            axum::http::StatusCode::NO_CONTENT.into_response()
        } else {
            axum::Json(json!({
                "id": ACTION_ID,
                "status": "Pending",
                "type": "CollectInvestigationPackage",
                "value": []
            }))
            .into_response()
        }
    })
}

